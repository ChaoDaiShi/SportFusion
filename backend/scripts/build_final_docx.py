    B(doc, 'W3——行业代码权重（权重0.25）：根据行业代码类型赋予差异化系数。直接体育代码W3=0.85（以体育为主业的高先验概率），间接相关代码W3=0.30（可能含体育的中等先验概率），无关代码W3=0（无先验信息，完全依赖文本分析）。该维度将行业分类体系的结构性信息以先验概率的形式引入模型。')
    B(doc, 'W4——业态覆盖度（权重0.10）：sport_category_count / 9（9为总业态数）。该维度衡量企业体育业务的多元化程度——同时涉及多个体育业态（如赛事+培训+用品）的企业，其体育投入通常比单一业态的企业更深入，给予更高的综合权重。')
