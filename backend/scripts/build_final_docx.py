# ============= HELPERS =============
def P(doc, text, font='SimSun', sz=12, bold=False, align=None, af=6, indent=None, ls=1.5):
    pp = doc.add_paragraph()
    run = pp.add_run(str(text))
    run.font.name = font
    run._element.rPr.rFonts.set(qn('w:eastAsia'), font)
    run.font.size = Pt(sz)
    run.bold = bold
    if align is not None: pp.alignment = align
    pp.paragraph_format.space_after = Pt(af)
    pp.paragraph_format.line_spacing = ls
    if indent: pp.paragraph_format.first_line_indent = Cm(indent)
    return pp

def H(doc, text, level=1):
    """Set heading with Word built-in style for TOC compatibility.
    level: 0=Title(no style), 1=Heading1, 2=Heading2, 3=Heading3"""
    if level == 0:
        # Cover title: no heading style, just formatted paragraph
        P(doc, text, font='SimHei', sz=22, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, af=18, ls=1.5)
        return
    # Map to Word heading style
    style_map = {1: 'Heading 1', 2: 'Heading 2', 3: 'Heading 3'}
    cfg = {1: (16, 'SimHei'), 2: (14, 'SimHei'), 3: (12, 'SimSun')}
    sz, fn = cfg.get(level, (12, 'SimSun'))
    sp = 14 if level == 1 else 10

    p = doc.add_paragraph()
    p.style = doc.styles[style_map[level]]
    # Clear default heading run and add custom formatted run
    run = p.add_run(str(text))
    run.font.name = fn
    run._element.rPr.rFonts.set(qn('w:eastAsia'), fn)
    run.font.size = Pt(sz)
    run.bold = True
    p.paragraph_format.space_after = Pt(sp)
    p.paragraph_format.line_spacing = 1.5

def B(doc, text):
    P(doc, text, font='SimSun', sz=12, indent=0.74, af=4, ls=1.5)

def IMG(doc, name, caption, w=5.5):
    path = CHART / name
    if path.exists():
        pp = doc.add_paragraph()
        pp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        pp.add_run().add_picture(str(path), width=Inches(w))
        P(doc, caption, font='SimSun', sz=10, align=WD_ALIGN_PARAGRAPH.CENTER, af=12, ls=1.0)

def TBL(doc, headers, rows, caption=''):
    if caption:
        P(doc, caption, font='SimSun', sz=10, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, af=4, ls=1.0)
    table = doc.add_table(rows=1+len(rows), cols=len(headers), style='Table Grid')
    table.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for i, hdr in enumerate(headers):
        cell = table.rows[0].cells[i]
        cell.text = str(hdr)
        for pr in cell.paragraphs:
            pr.alignment = WD_ALIGN_PARAGRAPH.CENTER
            for rn in pr.runs:
                rn.font.bold = True
                rn.font.size = Pt(10)
    for r, row in enumerate(rows):
        for c, val in enumerate(row):
            cell = table.rows[r+1].cells[c]
            cell.text = str(val)
            for pr in cell.paragraphs:
                pr.alignment = WD_ALIGN_PARAGRAPH.CENTER
                for rn in pr.runs:
                    rn.font.size = Pt(10)
    doc.add_paragraph()

def BR(doc):
    doc.add_page_break()

def add_toc(doc):
    """Add a Word TOC field that renders when opened."""
    H(doc, '目  录', level=0)
    paragraph = doc.add_paragraph()
    run = paragraph.add_run()
    fldChar1 = OxmlElement('w:fldChar')
    fldChar1.set(qn('w:fldCharType'), 'begin')
    run._r.append(fldChar1)
    instrText = OxmlElement('w:instrText')
    instrText.set(qn('xml:space'), 'preserve')
    instrText.text = ' TOC \\o "1-3" \\h \\z \\u '
    run._r.append(instrText)
    fldChar2 = OxmlElement('w:fldChar')
    fldChar2.set(qn('w:fldCharType'), 'separate')
    run._r.append(fldChar2)
    run2 = paragraph.add_run('（请在Word中右键此处，选择"更新域"以生成目录）')
    run2.font.size = Pt(10)
    run2.font.color.rgb = RGBColor(128, 128, 128)
    fldChar3 = OxmlElement('w:fldChar')
    fldChar3.set(qn('w:fldCharType'), 'end')
    run2._r.append(fldChar3)
    BR(doc)

