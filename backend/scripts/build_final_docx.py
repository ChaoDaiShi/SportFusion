    B(doc, '企业微观数据库中不包含营收数据，这是本研究面临的核心数据约束。传统方法在此约束下只能给出二值判定，而本研究创新性地构建了基于多维度特征加权的体育业务占比估算模型——SportRatio Model。')
    B(doc, '模型由四个维度的特征指标通过加权求和构成：')
    B(doc, 'W1——业务范围占比（权重0.40）：sport_business_lines / total_business_lines。该维度最直接地反映了体育业务在企业经营范围中的覆盖面。例如，一家企业有5条业务线，其中2条为体育，则W1 = 2/5 = 0.40。该维度的合理性基础在于：企业在工商登记中填报的业务活动通常按照重要性递减排序，体育业务线数量的占比与企业实际体育投入分配存在统计学上的正相关关系。')
